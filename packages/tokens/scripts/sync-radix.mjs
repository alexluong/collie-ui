// Regenerates src/primitive.tokens.json from @radix-ui/colors.
//
// The ramps are checked in rather than read at build time, so a generated brand
// ramp can replace a Radix one per theme without changing the build.
import * as radix from "@radix-ui/colors";
import { writeFileSync } from "node:fs";

// Every ramp a theme might point at. Light and dark are separate ramps rather
// than a media query, so a theme picks its polarity like any other value.
const HUES = ["gray", "blue", "red", "amber", "green", "sand", "bronze", "tomato", "grass"];

const tokens = {
  $description:
    "Primitive ramps, generated by scripts/sync-radix.mjs from @radix-ui/colors. Referenced only by the semantic layer. Step assignments follow Radix's documented scale semantics.",
};

for (const hue of HUES) {
  for (const scale of [hue, `${hue}Dark`]) {
    const source = radix[scale];
    tokens[scale] = { $type: "color" };
    for (let step = 1; step <= 12; step++) {
      // Dark scales key their steps by the base hue name: grayDark.gray1.
      const value = source[`${hue}${step}`];
      if (!value) throw new Error(`missing ${scale} step ${step}`);
      tokens[scale][step] = { $value: value };
    }
  }
}

tokens.white = { $type: "color", $value: "#ffffff" };
tokens.blackA = {
  $type: "color",
  6: { $value: "rgba(0, 0, 0, 0.15)" },
  9: { $value: "rgba(0, 0, 0, 0.45)" },
  11: { $value: "rgba(0, 0, 0, 0.65)" },
};
tokens.scale = {
  space: {
    $type: "dimension",
    1: { $value: "0.25rem" },
    2: { $value: "0.5rem" },
    3: { $value: "0.75rem" },
    4: { $value: "1rem" },
    6: { $value: "1.5rem" },
    8: { $value: "2rem" },
    12: { $value: "3rem" },
  },
};

writeFileSync("src/primitive.tokens.json", JSON.stringify(tokens, null, 2) + "\n");
console.log("primitives: synced from @radix-ui/colors");
