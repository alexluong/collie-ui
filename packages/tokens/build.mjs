// DTCG tokens -> CSS custom properties + a Tailwind @theme mapping + a contract.
//
// Two files come out of here and they do different jobs:
//
//   theme.css     raw `--collie-*` custom properties, per selector. Swapping
//                 [data-theme] / [data-density] rewrites these.
//   tailwind.css  `@theme inline` mapping Tailwind's utility namespaces onto
//                 those vars, so `bg-surface` resolves straight to
//                 `--collie-color-surface` without a second hop.
//
// The two layers exist because `--collie-*` is engine-neutral: Panda, a server
// -rendered template, or a Flutter export read those names, and tailwind.css is
// just the Tailwind adapter over them. Tailwind alone wouldn't need the split —
// semantic values could live directly in `@theme` and be overridden under
// [data-theme]. The prefix also keeps these from colliding with app-level vars
// when the system is copy-pasted into a monorepo that already has its own.
//
// Themes emit ONLY the tokens they override; everything else inherits from :root.

import StyleDictionary from "style-dictionary";
import { mkdirSync, readdirSync, readFileSync, rmSync, watch, writeFileSync } from "node:fs";
import { basename } from "node:path";

const PREFIX = "collie";

/**
 * Token path -> CSS custom property name.
 *
 * The role (`bg` / `fg` / `border`) is dropped for backgrounds because
 * Tailwind's utility prefix already carries it (`bg-surface`), and kept for
 * foreground and border where it would otherwise collide.
 */
function varName(path) {
  const [head, ...rest] = path;
  if (head === "color") {
    const [role, ...tail] = rest;
    const leaf = tail.join("-") === "default" ? "" : tail.join("-");
    if (role === "bg") return `--${PREFIX}-color-${leaf}`;
    return `--${PREFIX}-color-${role}${leaf ? `-${leaf}` : ""}`;
  }
  return `--${PREFIX}-${path.join("-").replace(/\.?-?default$/, "")}`;
}

StyleDictionary.registerFormat({
  name: "collie/css-vars",
  format: ({ dictionary, options }) => {
    const lines = dictionary.allTokens
      .map((t) => `  ${varName(t.path)}: ${t.$value ?? t.value};`)
      .sort();
    return `${options.selector} {\n${lines.join("\n")}\n}\n`;
  },
});

// The contract: every semantic token name, so CI can assert a theme defines
// them all rather than silently falling back to :root.
StyleDictionary.registerFormat({
  name: "collie/contract",
  format: ({ dictionary }) => {
    const names = dictionary.allTokens.map((t) => `  | "${varName(t.path)}"`).sort();
    return [
      "// Generated by packages/tokens/build.mjs — do not edit.",
      "export type CollieToken =",
      names.join("\n"),
      "  ;",
      "",
    ].join("\n");
  },
});

// Feeds the docs: the token reference is rendered from this, never hand-written.
StyleDictionary.registerFormat({
  name: "collie/json",
  format: ({ dictionary }) =>
    JSON.stringify(
      dictionary.allTokens.map((t) => ({
        name: varName(t.path),
        path: t.path,
        value: t.$value ?? t.value,
        reference: typeof t.original?.$value === "string" ? t.original.$value : undefined,
        description: t.$description ?? t.original?.$description,
      })),
      null,
      2,
    ) + "\n",
});

const PRIMITIVES = "src/primitive.tokens.json";
const SEMANTIC = "src/semantic.tokens.json";
const THEMES = "src/theme";
const DENSITIES = "src/density";

const scratch = `dist/.tmp-${process.pid}`;

/** Every leaf path the semantic layer defines — the contract a theme fills in. */
function semanticPaths() {
  const paths = new Set();
  const walk = (node, path) => {
    for (const [key, value] of Object.entries(node)) {
      if (key.startsWith("$")) continue;
      if (value.$value !== undefined) paths.add([...path, key].join("."));
      else walk(value, [...path, key]);
    }
  };
  walk(JSON.parse(readFileSync(SEMANTIC, "utf8")), []);
  return paths;
}

const SEMANTIC_PATHS = semanticPaths();

/**
 * A theme usually wants to say "use the dark ramps" rather than restate sixty
 * tokens. `$ramps: { gray: "grayDark" }` in a theme file is expanded here into
 * the full per-step overrides before Style Dictionary sees it.
 */
function expandRamps(file) {
  const source = JSON.parse(readFileSync(file, "utf8"));
  const ramps = source.$ramps;
  if (!ramps) return file;

  delete source.$ramps;
  const primitives = JSON.parse(readFileSync(PRIMITIVES, "utf8"));

  for (const [target, from] of Object.entries(ramps)) {
    const steps = Object.keys(primitives[from] ?? {}).filter((key) => !key.startsWith("$"));
    if (steps.length === 0) throw new Error(`${file}: no primitive ramp named "${from}"`);
    source[target] = {
      $type: "color",
      ...Object.fromEntries(steps.map((s) => [s, { $value: `{${from}.${s}}` }])),
    };
  }

  const expanded = `${scratch}/${basename(file)}`;
  writeFileSync(expanded, JSON.stringify(source, null, 2));
  return expanded;
}

function variants(dir) {
  return readdirSync(dir)
    .filter((file) => file.endsWith(".tokens.json"))
    .sort()
    .map((file) => ({
      name: file.replace(".tokens.json", ""),
      file: expandRamps(`${dir}/${file}`),
    }));
}

async function layer({ sources, filter, selector, destination, format = "collie/css-vars" }) {
  const sd = new StyleDictionary({
    source: sources,
    usesDtcg: true,
    log: { verbosity: "silent" },
    platforms: {
      css: {
        transformGroup: "css",
        buildPath: destination.startsWith("_") ? `${scratch}/` : "dist/",
        files: [{ destination, format, filter, options: { selector, outputReferences: false } }],
      },
    },
  });
  await sd.buildAllPlatforms();
}

// A theme or density file may redefine a primitive ramp, a semantic token, or
// both. Either way the emitted block is the whole semantic layer resolved
// against it, so a theme never restates what it does not change — and a theme
// that repoints one ramp gets every token derived from it for free.
const isSemantic = (token) => SEMANTIC_PATHS.has(token.path.join("."));

async function buildTokens() {
  mkdirSync(scratch, { recursive: true });
  mkdirSync("dist", { recursive: true });

  const themes = variants(THEMES);
  const densities = variants(DENSITIES);

  await layer({
    sources: [PRIMITIVES, SEMANTIC],
    filter: isSemantic,
    selector: ":root",
    destination: "_base.css",
  });

  for (const theme of themes) {
    await layer({
      sources: [PRIMITIVES, SEMANTIC, theme.file],
      filter: isSemantic,
      selector: `[data-theme="${theme.name}"]`,
      destination: `_theme-${theme.name}.css`,
    });
  }

  for (const density of densities) {
    await layer({
      sources: [PRIMITIVES, SEMANTIC, density.file],
      filter: isSemantic,
      selector: `[data-density="${density.name}"]`,
      destination: `_density-${density.name}.css`,
    });
  }

  await layer({
    sources: [PRIMITIVES, SEMANTIC],
    filter: isSemantic,
    selector: ":root",
    destination: "contract.d.ts",
    format: "collie/contract",
  });
  await layer({
    sources: [PRIMITIVES, SEMANTIC],
    filter: isSemantic,
    selector: ":root",
    destination: "tokens.json",
    format: "collie/json",
  });
  await layer({
    sources: [PRIMITIVES],
    filter: (token) => token.filePath.endsWith("primitive.tokens.json"),
    selector: ":root",
    destination: "primitives.json",
    format: "collie/json",
  });

  const layerFiles = [
    "_base.css",
    ...themes.map((theme) => `_theme-${theme.name}.css`),
    ...densities.map((density) => `_density-${density.name}.css`),
  ];

  // Stitch the layers into one stylesheet. Style Dictionary only writes to disk,
  // so the per-layer output goes to a process-unique scratch directory first —
  // `mise run dev` can have a one-shot build and the watcher running at once, and
  // shared temp filenames would have them clobbering each other mid-read.
  const parts = layerFiles.map((file) => readFileSync(`${scratch}/${file}`, "utf8"));
  writeFileSync(
    "dist/theme.css",
    `/* Generated by packages/tokens/build.mjs — do not edit. */\n\n${parts.join("\n")}`,
  );
  rmSync(scratch, { recursive: true, force: true });

  // Tailwind namespace mapping. Only these namespaces generate utilities, so this
  // file is also the list of what recipes are allowed to say.
  const semantic = JSON.parse(readFileSync(SEMANTIC, "utf8"));
  const colorVars = [];
  for (const [role, group] of Object.entries(semantic.color)) {
    if (role.startsWith("$")) continue;
    const walk = (node, path) => {
      for (const [k, v] of Object.entries(node)) {
        if (k.startsWith("$")) continue;
        if (v.$value !== undefined) walk_leaf([...path, k]);
        else walk(v, [...path, k]);
      }
    };
    const walk_leaf = (path) => {
      const cssVar = varName(["color", role, ...path]);
      const utility = cssVar.replace(`--${PREFIX}-color-`, "");
      colorVars.push(`  --color-${utility}: var(${cssVar});`);
    };
    walk(group, []);
  }
  const scaleVars = (group, prefix, tokenGroup = group) =>
    Object.keys(semantic[group] ?? {})
      .filter((k) => !k.startsWith("$"))
      .map((k) => `  --${prefix}-${k}: var(--${PREFIX}-${tokenGroup}-${k});`);

  const spaceVars = scaleVars("space", "spacing");
  const radiusVars = scaleVars("radius", "radius");
  const fontVars = scaleVars("font", "font");
  const shadowVars = scaleVars("shadow", "shadow");
  const textVars = scaleVars("text", "text");
  const leadingVars = scaleVars("leading", "leading");
  const weightVars = scaleVars("weight", "font-weight", "weight");
  const containerVars = scaleVars("container", "container");

  writeFileSync(
    "dist/tailwind.css",
    [
      "/* Generated by packages/tokens/build.mjs — do not edit. */",
      '@import "./theme.css";',
      "",
      "/* Tailwind's own scales are dropped: the only utilities that exist are the",
      "   ones named here, so `bg-blue-500`, `p-4` and `text-2xl` do not compile. */",
      "@theme {",
      "  --spacing: initial;",
      "  --color-*: initial;",
      "  --radius-*: initial;",
      "  --text-*: initial;",
      "  --leading-*: initial;",
      "  --font-weight-*: initial;",
      "  --container-*: initial;",
      "}",
      "",
      "@theme inline {",
      "  --color-transparent: transparent;",
      "  --color-current: currentColor;",
      ...colorVars.sort(),
      ...spaceVars,
      ...radiusVars,
      ...fontVars,
      ...shadowVars,
      ...textVars,
      ...leadingVars,
      ...weightVars,
      ...containerVars,
      "}",
      "",
    ].join("\n"),
  );

  console.log(
    `tokens: wrote theme.css (${themes.map((t) => t.name).join(", ")}), tailwind.css, contract.d.ts`,
  );
}

await buildTokens();

// `--watch` keeps the generated CSS in step with the DTCG source while a dev
// server is running. The output lands in dist/, which the workshop imports by
// relative path so Vite picks the change up and hot-reloads it.
if (process.argv.includes("--watch")) {
  let queued;
  watch("src", { recursive: true }, () => {
    clearTimeout(queued);
    // Editors write in bursts; one rebuild per burst is enough.
    queued = setTimeout(() => {
      buildTokens().catch((error) => console.error("tokens: build failed\n", error));
    }, 50);
  });
  console.log("tokens: watching src/ for changes");
}
