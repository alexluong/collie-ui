#!/usr/bin/env node
// Assigns this worktree its own range of dev ports.
//
// Several worktrees of Collie UI are often checked out at once, and each needs
// ports nothing else is using — otherwise the second Storybook to start either
// fails or silently lands somewhere unexpected. The range is seeded from the
// worktree's directory name so it's stable across restarts, then checked to be
// actually free (a hash alone can collide, and something unrelated may already
// hold the port). Written to a gitignored .env that mise loads.

import { createServer } from "node:net";
import { createHash } from "node:crypto";
import { existsSync, writeFileSync } from "node:fs";
import { basename, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const PORTS_PER_WORKTREE = 10;
const FIRST_PORT = 6000;
const SLOTS = 90;

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const envPath = resolve(root, ".env");

if (existsSync(envPath)) {
  console.log(".env already exists — leaving it alone. Delete it to reassign ports.");
  process.exit(0);
}

function isFree(port) {
  // Bind the way a dev server does — all interfaces, dual-stack. Probing
  // 127.0.0.1 specifically does NOT conflict with a listener holding `*:port`
  // on IPv6, so it reports busy ports as free.
  return new Promise((done) => {
    const server = createServer()
      .once("error", () => done(false))
      .once("listening", () => server.close(() => done(true)))
      .listen(port);
  });
}

const name = basename(root);
const seed = parseInt(createHash("sha256").update(name).digest("hex").slice(0, 8), 16) % SLOTS;

let base;
for (let attempt = 0; attempt < SLOTS; attempt++) {
  const candidate = FIRST_PORT + ((seed + attempt) % SLOTS) * PORTS_PER_WORKTREE;
  // Only the ports actually in use need to be free; the rest of the range is
  // reserved for whatever this worktree runs later.
  if ((await isFree(candidate)) && (await isFree(candidate + 1))) {
    base = candidate;
    break;
  }
}

if (base === undefined) {
  console.error(
    `No free port range found between ${FIRST_PORT} and ${FIRST_PORT + SLOTS * PORTS_PER_WORKTREE}.`,
  );
  process.exit(1);
}

writeFileSync(
  envPath,
  `# Generated by scripts/setup-env.mjs for the "${name}" worktree.
# Seeded from the directory name, then checked to be free, so parallel worktrees
# don't collide. Safe to edit — gitignored, and never regenerated once it exists.
PORT_BASE=${base}
PORT_STORYBOOK=${base}
PORT_PLAYROOM=${base + 1}
`,
);

console.log(`Wrote .env for "${name}" — storybook :${base}, playroom :${base + 1}`);
